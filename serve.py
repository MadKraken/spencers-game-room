"""Serve Spencer's Game Room locally with caching turned off, so edits show up on a normal reload.

Usage: python serve.py [port]    (default port 8765, then open http://localhost:8765)
"""
import functools
import http.server
import os
import sys


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8765
    root = os.path.dirname(os.path.abspath(__file__))
    handler = functools.partial(NoCacheHandler, directory=root)
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"Spencer's Game Room: http://localhost:{port}")
        httpd.serve_forever()
